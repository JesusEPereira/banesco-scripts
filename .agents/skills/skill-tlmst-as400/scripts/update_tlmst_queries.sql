WHERE TLMTID IN (
    'BAN1740C01', 'BAN1740C02', 'BAN1740C03', 'BAN1740C04', 'BAN1740C05', 
    'BAN1740C06', 'BAN1740C07', 'BAN1740C08', 'BAN1740C09', 'BAN1740C10'
